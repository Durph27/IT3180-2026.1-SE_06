"""Generate the reviewed HTTP boundary from the checked-in contract.

Run from repository root after a contract change. Never regenerate a migration
that has already been deployed: create a new migration instead.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
spec = json.loads((root / 'docs/api/openapi.json').read_text(encoding='utf-8'))
resources = root / 'backend/src/main/resources'
java = root / 'backend/src/main/java/com/bluemoon/backend/api'

groups = {
    'Account': ['auth', 'users'],
    'Rbac': ['roles', 'permissions'],
    'Residence': ['buildings', 'apartments', 'households', 'occupancies'],
    'Resident': ['residents'],
    'ResidenceChange': ['residence-changes'],
    'Fees': ['fee-types', 'fee-rates', 'billing-periods', 'invoices', 'contribution-campaigns', 'contributions'],
    'Payments': ['payments', 'receipts'],
    'Maintenance': ['maintenance-funds', 'maintenance-rounds'],
}
routes = {}
for group, prefixes in groups.items():
    methods = []
    for path, operations in spec['paths'].items():
        if path.split('/')[1] not in prefixes or path.endswith('/generate-invoices'):
            continue
        for method, op in operations.items():
            if method not in ('get', 'post', 'patch', 'put', 'delete'):
                continue
            key = method.upper() + ' ' + path
            params = [spec['components']['parameters'][p['$ref'].split('/')[-1]] if '$ref' in p else p for p in op.get('parameters', [])]
            body = op.get('requestBody', {}).get('content', {}).get('application/json', {}).get('schema')
            status = next(int(s) for s in op['responses'] if s.startswith('2'))
            routes[key] = {'permission': op['x-permission'], 'parameters': params, 'body': body, 'status': status}
            methods.append(f'''    @RequestMapping(value = "{path}", method = RequestMethod.{method.upper()})
    public ResponseEntity<?> {op['operationId']}(@PathVariable Map<String, String> path,
            @RequestParam Map<String, String> query, @RequestBody(required = false) Map<String, Object> body,
            HttpServletRequest request) {{
        return api.execute("{key}", path, query, body, request);
    }}
''')
    (java / f'{group}Controller.java').write_text('''package com.bluemoon.backend.api;

import jakarta.servlet.http.HttpServletRequest;
import java.util.Map;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

/** HTTP bindings generated by tools/sync_sprint1_contract.py; business logic lives in services. */
@RestController
@RequestMapping("/api")
public class ''' + group + '''Controller {
    private final SprintApi api;
    public ''' + group + '''Controller(SprintApi api) { this.api = api; }

''' + '\n'.join(methods) + '}\n', encoding='utf-8')

for path, operations in spec['paths'].items():
    for method, operation in operations.items():
        if method in ('get','post','patch','put','delete'):
            operation['x-implemented'] = method.upper()+' '+path in routes or path in ('/hello','/health')
(root / 'docs/api/openapi.json').write_text(json.dumps(spec,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(f'Generated {len(routes)} HTTP bindings. Runtime schemas load directly from OpenAPI.')
